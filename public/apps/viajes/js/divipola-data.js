/**
 * Normaliza un texto eliminando tildes y mayúsculas
 */
function cleanStr(str) {
  if (!str) return '';
  return str
    .toString()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim();
}

/**
 * Busca municipios en el catálogo DIVIPOLA
 * @param {string} query Texto a buscar o código DANE
 * @returns {Array} Coincidencias encontradas
 */
export function searchDivipola(query) {
  if (!query || typeof query !== 'string') return [];
  const q = cleanStr(query);
  return DIVIPOLA_COLOMBIA.filter(item => {
    return (
      item.codigo.startsWith(q) ||
      cleanStr(item.municipio).includes(q) ||
      cleanStr(item.departamento).includes(q) ||
      cleanStr(`${item.municipio} (${item.departamento})`).includes(q)
    );
  });
}

/**
 * Obtiene el registro DIVIPOLA por código DANE exacto
 */
export function getDivipolaByCode(code) {
  if (!code) return null;
  const c = String(code).trim();
  return DIVIPOLA_COLOMBIA.find(item => item.codigo === c) || null;
}

/**
 * Formatea la etiqueta oficial DIVIPOLA para visualización e impresión
 * Ejemplo: "86865 - Villagarzón (Putumayo)"
 */
export function formatDivipolaLabel(item) {
  if (!item) return '';
  if (typeof item === 'string') {
    const found = getDivipolaByCode(item) || DIVIPOLA_COLOMBIA.find(d => cleanStr(d.municipio) === cleanStr(item));
    if (found) return `${found.codigo} - ${found.municipio} (${found.departamento})`;
    return item;
  }
  return `${item.codigo} - ${item.municipio} (${item.departamento})`;
}
